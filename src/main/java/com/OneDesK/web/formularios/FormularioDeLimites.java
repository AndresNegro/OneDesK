package com.OneDesK.web.formularios;

/** El minimo y el maximo de gramos que puede tener una compra. */
public class FormularioDeLimites {

	private int minimo;
	private int maximo;

	public int getMinimo() {
		return minimo;
	}

	public void setMinimo(int minimo) {
		this.minimo = minimo;
	}

	public int getMaximo() {
		return maximo;
	}

	public void setMaximo(int maximo) {
		this.maximo = maximo;
	}
}
